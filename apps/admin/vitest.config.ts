import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { cloudflareTest, readD1Migrations } from '@cloudflare/vitest-plugin';
import { defineConfig } from 'vitest/config';
import { TEST_MANIFEST as CONSOLE_MANIFEST } from '../console/scripts/gen-wrangler.ts';
import { COMPATIBILITY_DATE, TEST_MANIFEST, testWranglerConfig } from './scripts/gen-wrangler.ts';

// The admin Worker under test runs from its generated config (bindings, assets, cron), without Hyperdrive: the tests
// swap in an in-memory ops store (src/ops.ts `opsSource`), and test-ops/ runs the store's SQL on PGlite. Its `API` and
// `CONSOLE` service bindings reach the real API and console Workers (bundled here with wrangler's dry run) as auxiliary
// Workers under the names the config binds, so every staff route and cron step crosses real service bindings into the
// real `AdminRpc` and `StaffRpc`. The tests share both Workers' D1s (HOT_DB, CONSOLE_TEST_DB) to seed and inspect them.
// Nothing reaches a network: the Access certs, Resend and NEAR RPC are answered by stubs of the isolate's fetch; the
// API's own NEAR RPC is an invalid host.
const here = (p: string) => new URL(p, import.meta.url).pathname;

const TEST_WRANGLER_CONFIG = here('./wrangler.vitest.jsonc');
writeFileSync(TEST_WRANGLER_CONFIG, `// Generated by vitest.config.ts (scripts/gen-wrangler.ts testWranglerConfig): never edit or commit.\n${JSON.stringify(testWranglerConfig(), null, 2)}\n`);

/** Bundles a Worker into one module (gitignored `.wrangler/`), exactly as `wrangler deploy` would build it. */
function bundle(name: string, dirName: string, alias: Record<string, string> = {}): string {
  const dir = here(`./.wrangler/${dirName}-under-test`);
  mkdirSync(dir, { recursive: true });
  const app = here(`../${dirName}`);
  const config = `${dir}/wrangler.jsonc`;
  writeFileSync(config, JSON.stringify({ name, main: `${app}/src/index.ts`, compatibility_date: COMPATIBILITY_DATE, compatibility_flags: ['nodejs_compat'], alias }));
  execFileSync(here('./node_modules/.bin/wrangler'), ['deploy', '--dry-run', '--outdir', `${dir}/out`, '-c', config], { cwd: app, stdio: 'pipe', env: { ...process.env, WRANGLER_SEND_METRICS: 'false' } });
  return `${dir}/out/index.js`;
}

