#!/usr/bin/env node
// Writes src/unicode-age.ts: the code points assigned AFTER the cutoff Unicode version (D156), from Unicode's
// DerivedAge.txt of the version tr46 implements. normalizeEmail refuses any of them, so the runtime's own Unicode data
// (String.prototype.normalize inside tr46) never meets a character it predates: the result is the same on every
// target runtime. Changing the cutoff or the source changes which addresses are accepted: frozen at the address freeze
// (test/vectors.test.ts pins the table's hash).
//
// DerivedAge.txt is Unicode, Inc.'s data under the Unicode License v3: its notice is in ../LICENSE-Unicode.txt and the
// README's "Unicode data licence", not in the generated file, whose bytes the freeze guard pins (D791).
//
//   curl -sSfLo DerivedAge.txt https://www.unicode.org/Public/18.0.0/ucd/DerivedAge.txt
//   node packages/email/scripts/update-unicode-age.mjs DerivedAge.txt 18.0.0 15.0
//
// No network here; the file is passed in.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'unicode-age.ts');
const [file, version, cutoff] = process.argv.slice(2);
if (!file || !/^\d+\.\d+\.\d+$/.test(version ?? '') || !/^\d+\.\d+$/.test(cutoff ?? '')) {
  console.error('usage: update-unicode-age.mjs <DerivedAge.txt> <its Unicode version, e.g. 18.0.0> <cutoff, e.g. 15.0>');
  process.exit(2);
}
const text = readFileSync(file, 'utf8');
if (!text.startsWith(`# DerivedAge-${version}.txt`)) throw new Error(`${file} is not DerivedAge-${version}.txt`);
const sha256 = createHash('sha256').update(text, 'utf8').digest('hex');

const num = (v) => v.split('.').map(Number);
const after = (age, cut) => {
  const [a1, a2] = num(age);
  const [c1, c2] = num(cut);
  return a1 > c1 || (a1 === c1 && a2 > c2);
};

const ranges = [];
for (const line of text.split('\n')) {
  const m = /^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(\d+\.\d+)\s*#/.exec(line);
  if (!m) continue;
  if (!after(m[3], cutoff)) continue;
  ranges.push([parseInt(m[1], 16), parseInt(m[2] ?? m[1], 16)]);
}
ranges.sort((x, y) => x[0] - y[0]);
const merged = [];
for (const r of ranges) {
  const last = merged.at(-1);
  if (last && r[0] <= last[1] + 1) last[1] = Math.max(last[1], r[1]);
  else merged.push([...r]);
}
const count = merged.reduce((n, [lo, hi]) => n + hi - lo + 1, 0);
const hex = (n) => n.toString(16).toUpperCase().padStart(4, '0');
const body = merged.map(([lo, hi]) => (lo === hi ? hex(lo) : `${hex(lo)}..${hex(hi)}`));
const lines = [];
for (let i = 0; i < body.length; i += 8) lines.push(body.slice(i, i + 8).join(' '));

const out = `// GENERATED by scripts/update-unicode-age.mjs: do not edit by hand. FROZEN at the address freeze (D156).
//
// Code points assigned after Unicode ${cutoff}, which normalizeEmail refuses so that every target runtime's own
// Unicode data agrees on the result (tr46 calls String.prototype.normalize).
// Source: https://www.unicode.org/Public/${version}/ucd/DerivedAge.txt
// Source sha256: ${sha256}
// Ranges: ${merged.length}; code points: ${count}.

export const UNICODE_AGE_SOURCE = Object.freeze({
  file: 'DerivedAge-${version}.txt',
  sha256: '${sha256}',
  cutoff: '${cutoff}',
  ranges: ${merged.length},
  codePoints: ${count},
});

/** Inclusive hex ranges (\`lo..hi\` or a single code point), sorted, merged, space or newline separated. */
export const ASSIGNED_AFTER_CUTOFF = \`
${lines.join('\n')}
\`;
`;
writeFileSync(OUT, out);
console.log(`wrote ${OUT}: ${merged.length} ranges, ${count} code points assigned after ${cutoff}`);
