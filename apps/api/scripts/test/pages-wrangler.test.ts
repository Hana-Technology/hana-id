import { existsSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { type Manifest, loadEnv, manifestSchema } from '@hana-id/env';
import { afterEach, describe, expect, it } from 'vitest';
import { COMPATIBILITY_DATE } from '../gen-wrangler.ts';
import { PAGES_CONFIG_FILES, pagesAssetsDir, pagesPlacement, pagesWranglerConfig, workersDevHost, writePagesWranglerConfigs } from '../pages-wrangler.ts';

const apiDir = resolve(fileURLToPath(import.meta.url), '..', '..', '..');
// sandbox-dev as deployed carries identityToken (its iss pins apiUrl), which these tests rewrite.
const { identityToken: _deployedIdentity, ...withoutIdentity } = loadEnv('sandbox-dev');
const manifest: Manifest = withoutIdentity;

const dirs: string[] = [];
const tmp = (): string => {
  const d = mkdtempSync(join(tmpdir(), 'hana-pages-wrangler-'));
  dirs.push(d);
  return d;
};
afterEach(() => {
  for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true });
});

/** A manifest variant, validated by the real schema (so every case is one the schema accepts). */
const variant = (patch: Partial<Manifest>): Manifest => manifestSchema.parse({ ...manifest, ...patch });

const readConfig = (path: string): Record<string, unknown> => {
  const text = readFileSync(path, 'utf8');
  expect(text.startsWith('// Generated by apps/api/scripts/gen-wrangler.ts from envs/')).toBe(true);
  return JSON.parse(text.slice(text.indexOf('\n') + 1)) as Record<string, unknown>;
};

describe('page Worker configs', () => {
  it('sandbox-dev: two workers.dev Workers named after their hostnames, preview URLs off', () => {
    const vault = pagesWranglerConfig(manifest, 'vault', COMPATIBILITY_DATE);
    const auth = pagesWranglerConfig(manifest, 'auth', COMPATIBILITY_DATE);
    expect(vault).toMatchObject({ name: 'hana-id-vault-sandbox-dev', workers_dev: true, preview_urls: false, main: 'src/pages/vault-worker.ts', compatibility_date: COMPATIBILITY_DATE });
    expect(auth).toMatchObject({ name: 'hana-id-auth-sandbox-dev', workers_dev: true, preview_urls: false, main: 'src/pages/auth-worker.ts', compatibility_date: COMPATIBILITY_DATE });
    // workers.dev serves `<name>.<subdomain>.workers.dev`, so the name gives back exactly the manifest origin.
    for (const [config, origin] of [[vault, manifest.vaultOrigin], [auth, manifest.authOrigin]] as const) {
      expect(`https://${String(config.name)}.${workersDevHost(new URL(manifest.apiUrl).hostname)!.subdomain}.workers.dev`).toBe(origin);
      expect(config).not.toHaveProperty('routes');
    }
  });

  it("binds each Worker to its own origin's built pages, with the Worker run first and no HTML or 404 handling", () => {
    for (const origin of ['vault', 'auth'] as const) {
      const config = pagesWranglerConfig(manifest, origin, COMPATIBILITY_DATE);
      expect(config.assets).toEqual({
        directory: `../../packages/web/dist/pages/sandbox-dev/${origin}`,
        binding: 'ASSETS',
        run_worker_first: true,
        html_handling: 'none',
        not_found_handling: 'none',
      });
      // Relative to apps/api, where the config is written.
      expect(resolve(apiDir, pagesAssetsDir(manifest.name, origin))).toBe(resolve(apiDir, '..', '..', 'packages', 'web', 'dist', 'pages', manifest.name, origin));
    }
  });

  it('vault: only VAULT_ORIGIN, and a service binding to the API Worker for /vault', () => {
    const config = pagesWranglerConfig(manifest, 'vault', COMPATIBILITY_DATE);
    expect(config.vars).toEqual({ VAULT_ORIGIN: manifest.vaultOrigin });
    expect(config.services).toEqual([{ binding: 'API', service: manifest.cloudflare.workerName }]);
  });

  it('auth: AUTH_ORIGIN plus apiUrl and rpc for the CSP, and no service binding', () => {
    const config = pagesWranglerConfig(manifest, 'auth', COMPATIBILITY_DATE);
    // sandbox-dev sets rpcFallback, which joins the export page's connect-src.
    expect(config.vars).toEqual({ AUTH_ORIGIN: manifest.authOrigin, API_URL: manifest.apiUrl, NEAR_RPC: manifest.rpc, NEAR_RPC_FALLBACK: manifest.rpcFallback });
    expect(config).not.toHaveProperty('services');
    const { rpcFallback: _, ...noFallback } = manifest;
    expect(pagesWranglerConfig(manifestSchema.parse(noFallback), 'auth', COMPATIBILITY_DATE).vars).toEqual({ AUTH_ORIGIN: manifest.authOrigin, API_URL: manifest.apiUrl, NEAR_RPC: manifest.rpc });
    // rpcFallback joins the export page's connect-src when the manifest sets it.
    const fb = pagesWranglerConfig(variant({ rpcFallback: 'https://rpc.fallback.example' }), 'auth', COMPATIBILITY_DATE);
    expect(fb.vars).toEqual({ AUTH_ORIGIN: manifest.authOrigin, API_URL: manifest.apiUrl, NEAR_RPC: manifest.rpc, NEAR_RPC_FALLBACK: 'https://rpc.fallback.example' });
  });

  it('carries no secret, D1 or Durable Object binding', () => {
    for (const origin of ['vault', 'auth'] as const) {
      const config = pagesWranglerConfig(manifest, origin, COMPATIBILITY_DATE);
      const text = JSON.stringify(config);
      expect(text).not.toMatch(/ed25519:|RELAYER_KEYS|KEYS_UPDATER_KEY|VAULT_KEK/u);
      expect(config).not.toHaveProperty('d1_databases');
      expect(config).not.toHaveProperty('durable_objects');
      expect(config).not.toHaveProperty('triggers');
    }
  });

  it('a custom hostname becomes a Custom Domain route on a Worker named after the API Worker', () => {
    const m = variant({ name: 'prod-test', vaultOrigin: 'https://vault.hana.example', authOrigin: 'https://auth.hana-login.example' });
    expect(pagesPlacement(m, 'vault')).toEqual({
      name: `${m.cloudflare.workerName}-vault`,
      workers_dev: false,
      preview_urls: false,
      routes: [{ pattern: 'vault.hana.example', custom_domain: true }],
    });
    expect(pagesPlacement(m, 'auth')).toMatchObject({ name: `${m.cloudflare.workerName}-auth`, routes: [{ pattern: 'auth.hana-login.example', custom_domain: true }] });
  });

  it('refuses a custom hostname with a port (Custom Domains have none)', () => {
    const m = variant({ name: 'prod-test', vaultOrigin: 'https://vault.hana.example:8443', authOrigin: 'https://auth.hana-login.example' });
    expect(() => pagesPlacement(m, 'vault')).toThrow(/can't have a port/u);
  });

  it('refuses workers.dev outside dev envs', () => {
    // Different accounts, so the schema's cross-site rule for non-dev envs holds; workers.dev itself is what's refused.
    const m = variant({ name: 'prod-test', vaultOrigin: 'https://v.acct1.workers.dev', authOrigin: 'https://a.acct2.workers.dev' });
    expect(() => pagesWranglerConfig(m, 'vault', COMPATIBILITY_DATE)).toThrow(/workers\.dev hostnames are for local\*\/sandbox\* envs only/u);
    expect(() => pagesWranglerConfig(m, 'auth', COMPATIBILITY_DATE)).toThrow(/workers\.dev hostnames are for local\*\/sandbox\* envs only/u);
  });

  it('refuses a workers.dev origin on another subdomain than a workers.dev apiUrl (the service binding needs one account)', () => {
    const m = variant({ vaultOrigin: 'https://hana-id-vault-sandbox-dev.someone-else.workers.dev' });
    expect(() => pagesPlacement(m, 'vault')).toThrow(/service binding needs both Workers on one account/u);
    // With the API on a custom domain there's nothing to compare against.
    expect(pagesPlacement({ ...m, apiUrl: 'https://api.hana.example' }, 'vault')).toMatchObject({ name: 'hana-id-vault-sandbox-dev', workers_dev: true });
  });

  it('refuses a page origin that is the API Worker itself', () => {
    // The schema refuses it already (a Hana origin is never apiUrl's origin); the placement refuses it on its own too.
    expect(() => variant({ vaultOrigin: manifest.apiUrl })).toThrow(/must not be apiUrl's origin/u);
    expect(() => pagesPlacement({ ...manifest, vaultOrigin: manifest.apiUrl }, 'vault')).toThrow(/names the API Worker itself/u);
  });

  it('refuses two origins that give one Worker name', () => {
    // Same label on two workers.dev subdomains, which only passes the subdomain check with the API elsewhere.
    const m = variant({ apiUrl: 'https://api.hana.example', vaultOrigin: 'https://hana-pages.one.workers.dev', authOrigin: 'https://hana-pages.two.workers.dev' });
    expect(() => pagesWranglerConfig(m, 'vault', COMPATIBILITY_DATE)).toThrow(/same Worker name hana-pages/u);
    expect(() => pagesWranglerConfig(m, 'auth', COMPATIBILITY_DATE)).toThrow(/same Worker name hana-pages/u);
  });

  it('local* envs: loopback origins become wrangler dev host and port, with no deployment target', () => {
    const m = variant({ name: 'local-test', vaultOrigin: 'http://127.0.0.1:8788', authOrigin: 'http://localhost:8789' });
    expect(pagesPlacement(m, 'vault')).toEqual({
      name: `${m.cloudflare.workerName}-vault`,
      workers_dev: false,
      preview_urls: false,
      dev: { ip: '127.0.0.1', port: 8788, local_protocol: 'http' },
    });
    expect(pagesPlacement(m, 'auth')).toMatchObject({ dev: { ip: 'localhost', port: 8789, local_protocol: 'http' } });
    expect(pagesPlacement(m, 'vault')).not.toHaveProperty('routes');
  });

  it('refuses an env without vaultOrigin and authOrigin', () => {
    const { vaultOrigin: _v, authOrigin: _a, ...bare } = manifest;
    expect(() => pagesWranglerConfig(bare, 'vault', COMPATIBILITY_DATE)).toThrow(/needs vaultOrigin and authOrigin/u);
    expect(() => pagesWranglerConfig(bare, 'auth', COMPATIBILITY_DATE)).toThrow(/needs vaultOrigin and authOrigin/u);
  });

  it('workersDevHost parses only <worker>.<subdomain>.workers.dev', () => {
    expect(workersDevHost('hana-id-vault-sandbox-dev.tingtc.workers.dev')).toEqual({ worker: 'hana-id-vault-sandbox-dev', subdomain: 'tingtc' });
    expect(workersDevHost('tingtc.workers.dev')).toBeNull();
    expect(workersDevHost('a.b.c.workers.dev')).toBeNull();
    expect(workersDevHost('vault.workers.dev.example')).toBeNull();
    expect(workersDevHost('-a.b.workers.dev')).toBeNull();
  });
});

describe('writePagesWranglerConfigs', () => {
  it('writes wrangler.vault.jsonc and wrangler.auth.jsonc', () => {
    const dir = tmp();
    const paths = writePagesWranglerConfigs(manifest, COMPATIBILITY_DATE, dir);
    expect(paths).toEqual([join(dir, PAGES_CONFIG_FILES.vault), join(dir, PAGES_CONFIG_FILES.auth)]);
    expect(readConfig(paths[0]!)).toEqual(pagesWranglerConfig(manifest, 'vault', COMPATIBILITY_DATE));
    expect(readConfig(paths[1]!)).toEqual(pagesWranglerConfig(manifest, 'auth', COMPATIBILITY_DATE));
  });

  it('writes neither file when either origin is refused', () => {
    const dir = tmp();
    const m = variant({ authOrigin: 'https://hana-id-auth-sandbox-dev.someone-else.workers.dev' });
    expect(() => writePagesWranglerConfigs(m, COMPATIBILITY_DATE, dir)).toThrow();
    expect(existsSync(join(dir, PAGES_CONFIG_FILES.vault))).toBe(false);
    expect(existsSync(join(dir, PAGES_CONFIG_FILES.auth))).toBe(false);
  });
});
