import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { cloudflareTest, readD1Migrations } from '@cloudflare/vitest-plugin';
import { defineConfig } from 'vitest/config';
import { COMPATIBILITY_DATE, TEST_MANIFEST, testWranglerConfig } from './scripts/gen-wrangler.ts';

// The console Worker under test runs from its generated config (bindings, assets, rate limit, cron) with CONSOLE_DB
// migrated. Its `API` service binding reaches the real API Worker (apps/api, bundled here with wrangler's dry run) as an
// auxiliary Worker under the name the config binds, so the console's calls cross a real service binding into the real
// `ConsoleRpc` (C5 tested the entrypoints only directly). The API's hot DB is shared with the tests as HOT_DB (same D1
// id) so they can seed it; API_ADMIN, a test-only binding to the same Worker's AdminRpc, stands in for the admin
// Worker (C8) to propose and announce changes. Nothing reaches a network: NEAR RPC is an invalid host, unused here.
const here = (p: string) => new URL(p, import.meta.url).pathname;

const TEST_WRANGLER_CONFIG = here('./wrangler.vitest.jsonc');
writeFileSync(TEST_WRANGLER_CONFIG, `// Generated by vitest.config.ts (scripts/gen-wrangler.ts testWranglerConfig): never edit or commit.\n${JSON.stringify(testWranglerConfig(), null, 2)}\n`);

/** Bundles apps/api into one module (gitignored `.wrangler/`), exactly as `wrangler deploy` would build it. */
function bundleApi(): string {
  const dir = here('./.wrangler/api-under-test');
  mkdirSync(dir, { recursive: true });
  const api = here('../api');
  const config = `${dir}/wrangler.jsonc`;
  writeFileSync(
    config,
    JSON.stringify({ name: TEST_MANIFEST.cloudflare.workerName, main: `${api}/src/index.ts`, compatibility_date: COMPATIBILITY_DATE, compatibility_flags: ['nodejs_compat'], alias: { secp256k1: `${api}/src/shims/secp256k1.ts` } }),
  );
  execFileSync(here('./node_modules/.bin/wrangler'), ['deploy', '--dry-run', '--outdir', `${dir}/out`, '-c', config], { cwd: api, stdio: 'pipe', env: { ...process.env, WRANGLER_SEND_METRICS: 'false' } });
  return `${dir}/out/index.js`;
}

const HOT_DB_ID = 'hana-id-test-hot';

export default defineConfig(async () => {
  const migrations = await readD1Migrations(here('./migrations'));
  const apiMigrations = await readD1Migrations(here('../api/migrations'));
  const apiScript = bundleApi();
  return {
    plugins: [
      cloudflareTest({
        wrangler: { configPath: TEST_WRANGLER_CONFIG },
        miniflare: {
          // The console client's secret is a throwaway test value: Google's token endpoint is mocked in the tests.
          bindings: { TEST_MIGRATIONS: migrations, TEST_API_MIGRATIONS: apiMigrations, CONSOLE_GOOGLE_CLIENT_SECRET: 'test-console-client-secret' },
          d1Databases: { HOT_DB: HOT_DB_ID },
          serviceBindings: { API_ADMIN: { name: TEST_MANIFEST.cloudflare.workerName, entrypoint: 'AdminRpc' } },
          workers: [
            {
              name: TEST_MANIFEST.cloudflare.workerName,
              modules: true,
              scriptPath: apiScript,
              compatibilityDate: COMPATIBILITY_DATE,
              compatibilityFlags: ['nodejs_compat'],
              d1Databases: { DB: HOT_DB_ID },
              durableObjects: {
                RATE_LIMITER: { className: 'RateLimiter', useSQLite: true },
                RELAYER_KEY: { className: 'RelayerKey', useSQLite: true },
                LOGIN_RELAY: { className: 'LoginRelay', useSQLite: true },
              },
              bindings: {
                NEAR_RPC: 'https://rpc.test.invalid',
                SIGNER_ACCOUNT: TEST_MANIFEST.signer,
                RELAYER_ACCOUNT: TEST_MANIFEST.relayer,
                ENV_NAME: TEST_MANIFEST.name,
                MPC_ACCOUNT: TEST_MANIFEST.mpc,
                APP_CHANGE_DELAY_MS: String(TEST_MANIFEST.appChangeDelayMs),
                NETWORK: TEST_MANIFEST.network,
                REFUSED_ORIGINS: JSON.stringify(['https://api.test', 'https://vault.test', 'https://auth.test', 'https://console.test', 'https://console-auth.test', 'https://files.test', 'https://admin.test']),
                FILES_ORIGIN: TEST_MANIFEST.files!.origin,
                RELAYER_KEYS: '[]',
              },
            },
          ],
        },
      }),
    ],
    test: {
      include: ['test/**/*.test.ts'],
      setupFiles: ['./test/apply-migrations.ts'],
      testTimeout: 30_000,
      onConsoleLog: (log: string) => (process.env.LOG || !log.startsWith('{"level"') ? undefined : false),
    },
  };
});
