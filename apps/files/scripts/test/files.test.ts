// The files Worker's generated config and source checks (docs/batch-c-spec.md "Tests: Topology and config"): no secret,
// D1 or Hyperdrive; LOGOS its only binding, read only by code (no `put`/`delete` call in its source); where it is
// deployed follows from `files.origin`.
import { mkdtempSync, readFileSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { type Manifest, manifestSchema } from '@hana-id/env';
import { describe, expect, it } from 'vitest';
import { LOGO_KEY_RE } from '../../../../packages/console-core/src/rpc.ts';
import { LOGO_PATH_RE as CORE_LOGO_PATH_RE } from '../../../../packages/core/src/logo.ts';
import { LOGO_PATH_RE } from '../../src/rules.ts';
import { TEST_MANIFEST, filesPlacement, main, testWranglerConfig, wranglerConfig } from '../gen-wrangler.ts';

const srcDir = new URL('../../src/', import.meta.url).pathname;
/** Each source file's code without its comments (so a comment can name what the code must not do). */
const code = (t: string) => t.replace(/\/\*[\s\S]*?\*\//gu, '').replace(/^\s*\/\/.*$/gmu, '');
const sources = readdirSync(srcDir).filter((f) => f.endsWith('.ts')).map((f) => ({ f, text: code(readFileSync(join(srcDir, f), 'utf8')) }));

const withOrigin = (origin: string, name = TEST_MANIFEST.name): Manifest => ({ ...TEST_MANIFEST, name, files: { ...TEST_MANIFEST.files!, origin } });

describe('the files config', () => {
  it('validates as a manifest with every dashboard block (the test manifest is a real one)', () => {
    expect(manifestSchema.parse(TEST_MANIFEST)).toBeTruthy();
  });

  it('binds LOGOS and FILES_ORIGIN only: no secret, D1, Hyperdrive, service, other bucket, assets or cron', () => {
    const c = testWranglerConfig();
    expect(c).toEqual({
      $schema: 'node_modules/wrangler/config-schema.json',
      name: 'hana-id-files-test',
      main: 'src/index.ts',
      compatibility_date: '2026-10-01',
      workers_dev: false,
      preview_urls: false,
      routes: [{ pattern: 'files.test', custom_domain: true }],
      observability: { enabled: true, logs: { invocation_logs: false } },
      vars: { FILES_ORIGIN: 'https://files.test' },
      r2_buckets: [{ binding: 'LOGOS', bucket_name: 'hana-id-logos-test' }],
    });
    expect(JSON.stringify(c)).not.toMatch(/d1_databases|hyperdrive|services|STATEMENTS|EXPORTS|secret|assets|triggers/iu);
    // The manifest's account, when it names one (D404).
    const id = '0123456789abcdef0123456789abcdef';
    expect(wranglerConfig({ ...TEST_MANIFEST, cloudflare: { ...TEST_MANIFEST.cloudflare, accountId: id } })).toMatchObject({ account_id: id });
  });

  it('workers.dev only in a dev env and only under its own Worker name; a Custom Domain needs no port; loopback is wrangler dev', () => {
    expect(filesPlacement(withOrigin('https://hana-id-files-test.acct.workers.dev'))).toEqual({ workers_dev: true, preview_urls: false });
    expect(() => filesPlacement(withOrigin('https://other-name.acct.workers.dev'))).toThrow(/own workers.dev hostname/u);
    expect(() => filesPlacement(withOrigin('https://hana-id-files-test.acct.workers.dev', 'production'))).toThrow(/local\*\/sandbox\*/u);
    expect(() => filesPlacement(withOrigin('https://files.test:8443'))).toThrow(/port/u);
    expect(filesPlacement(withOrigin('http://localhost:8792', 'local-dev'))).toEqual({
      workers_dev: false,
      preview_urls: false,
      dev: { ip: 'localhost', port: 8792, local_protocol: 'http' },
    });
  });

  it('refuses a manifest without the files block', () => {
    const { files: _f, ...bare } = TEST_MANIFEST;
    expect(() => wranglerConfig(bare as Manifest)).toThrow(/no files block/u);
  });

  it('writes the file', () => {
    const dir = mkdtempSync(join(tmpdir(), 'files-gen-'));
    try {
      main(['sandbox-test'], { dir, loadManifest: () => TEST_MANIFEST });
      const text = readFileSync(join(dir, 'wrangler.jsonc'), 'utf8');
      expect(text.startsWith('// Generated by apps/files/scripts/gen-wrangler.ts from envs/sandbox-test.json')).toBe(true);
      expect(JSON.parse(text.slice(text.indexOf('\n') + 1))).toEqual(testWranglerConfig());
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});

describe('source checks', () => {
  it('no put or delete on LOGOS (read only by code, D74): get is its only call', () => {
    let gets = 0;
    for (const { f, text } of sources) {
      for (const m of text.matchAll(/LOGOS(\??\.|\]|\s*[,)])(\w*)/gu)) {
        expect(['get'], `${f}: LOGOS${m[1]}${m[2]}`).toContain(m[2]);
        gets += 1;
      }
      // The binding is never handed on (to a helper that could write it) or reached by a computed name.
      expect(text, f).not.toMatch(/LOGOS\s*[,;)]|\[\s*['"`]LOGOS/u);
      expect(text, f).not.toMatch(/\.(put|delete|createMultipartUpload|resumeMultipartUpload)\s*\(/u);
    }
    expect(gets).toBe(1);
  });

  it('no secret, cookie or other binding in the source', () => {
    for (const { f, text } of sources) expect(text, f).not.toMatch(/set-cookie|SECRET|_KEY\b|\bDB\b|HYPERDRIVE|STATEMENTS|EXPORTS/u);
  });

  it('serves the path of the key the console writes, as the protocol checks it', () => {
    const key = `logos/app_abc123/${'ab'.repeat(32)}.png`;
    expect(LOGO_KEY_RE.test(key)).toBe(true);
    expect(LOGO_PATH_RE.exec(`/${key}`)?.[1]).toBe(key);
    expect(CORE_LOGO_PATH_RE.test(`/${key}`)).toBe(true);
    // The three patterns are the same rule.
    expect(LOGO_PATH_RE.source.replace(/[()]/gu, '')).toBe(`^\\/${LOGO_KEY_RE.source.slice(1)}`.replace(/[()]/gu, ''));
    expect(CORE_LOGO_PATH_RE.source).toBe(`^\\/${LOGO_KEY_RE.source.slice(1)}`.replace(/[()]/gu, ''));
  });
});
