import { writeFileSync } from 'node:fs';
import { cloudflareTest } from '@cloudflare/vitest-plugin';
import { defineConfig } from 'vitest/config';
import { testWranglerConfig } from './scripts/gen-wrangler.ts';

// The files Worker under test runs from its generated config (the LOGOS bucket, FILES_ORIGIN), with Miniflare's local
// R2. The tests seed objects through the same binding; the Worker's source never writes it (scripts/test).
const TEST_WRANGLER_CONFIG = new URL('./wrangler.vitest.jsonc', import.meta.url).pathname;
writeFileSync(TEST_WRANGLER_CONFIG, `// Generated by vitest.config.ts (scripts/gen-wrangler.ts testWranglerConfig): never edit or commit.\n${JSON.stringify(testWranglerConfig(), null, 2)}\n`);

export default defineConfig({
  plugins: [cloudflareTest({ wrangler: { configPath: TEST_WRANGLER_CONFIG } })],
  test: {
    include: ['test/**/*.test.ts'],
    onConsoleLog: (log: string) => (process.env.LOG || !log.startsWith('{"level"') ? undefined : false),
  },
});
