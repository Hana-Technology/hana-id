import { execFileSync } from 'node:child_process';
import { createHash, generateKeyPairSync, randomBytes } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { cloudflareTest, readD1Migrations } from '@cloudflare/vitest-plugin';
import { defineConfig } from 'vitest/config';
import { COMPATIBILITY_DATE, TEST_MANIFEST, testWranglerConfig } from './scripts/gen-wrangler.ts';

// Throwaway keys per run: the signing key (primary) and a standby that stays off the Worker, and the three HMAC keys.
// Tests never reach SendGrid, Google, a NEAR RPC or KMS: every outbound call goes to an injected fake.
//
// The `API` service binding (D434) reaches the real API Worker (bundled here with wrangler's dry run, as the admin
// tests do) as an auxiliary Worker under the name the config binds, so every app lookup crosses a real service binding
// into the real `IssuerRpc`. The tests seed and change the API's D1 through API_TEST_DB, the same database: a test-only
// binding of the test isolate, never in the Worker's generated config.
function rsaKey(): { private: Record<string, string>; public: Record<string, string> } {
  const { privateKey } = generateKeyPairSync('rsa', { modulusLength: 2048, publicExponent: 65537 });
  const jwk = privateKey.export({ format: 'jwk' }) as Record<string, string>;
  const kid = createHash('sha256').update(`{"e":"${jwk.e}","kty":"RSA","n":"${jwk.n}"}`).digest('base64url');
  return { private: jwk, public: { kty: 'RSA', n: jwk.n!, e: jwk.e!, kid, use: 'sig', alg: 'RS256' } };
}
const primary = rsaKey();
const standby = rsaKey();

const TEST_WRANGLER_CONFIG = new URL('./wrangler.vitest.jsonc', import.meta.url).pathname;
writeFileSync(
  TEST_WRANGLER_CONFIG,
  `// Generated by vitest.config.ts (scripts/gen-wrangler.ts testWranglerConfig): never edit or commit.\n${JSON.stringify(testWranglerConfig([primary.public, standby.public], primary.public.kid!), null, 2)}\n`,
);

const here = (p: string) => new URL(p, import.meta.url).pathname;
const API_DB_ID = TEST_MANIFEST.cloudflare.d1Name;

/** Bundles the API Worker into one module (gitignored `.wrangler/`), exactly as `wrangler deploy` would build it. */
function bundleApi(): string {
  const dir = here('./.wrangler/api-under-test');
  mkdirSync(dir, { recursive: true });
  const app = here('../api');
  const config = `${dir}/wrangler.jsonc`;
  const alias = { secp256k1: here('../api/src/shims/secp256k1.ts') };
  writeFileSync(config, JSON.stringify({ name: TEST_MANIFEST.cloudflare.workerName, main: `${app}/src/index.ts`, compatibility_date: COMPATIBILITY_DATE, compatibility_flags: ['nodejs_compat'], alias }));
  execFileSync(here('./node_modules/.bin/wrangler'), ['deploy', '--dry-run', '--outdir', `${dir}/out`, '-c', config], { cwd: app, stdio: 'pipe', env: { ...process.env, WRANGLER_SEND_METRICS: 'false' } });
  return `${dir}/out/index.js`;
}

export default defineConfig(async () => {
  const migrations = await readD1Migrations(new URL('./migrations', import.meta.url).pathname);
  const apiMigrations = await readD1Migrations(new URL('../api/migrations', import.meta.url).pathname);
  const apiScript = bundleApi();
  return {
    plugins: [
      cloudflareTest({
        wrangler: { configPath: TEST_WRANGLER_CONFIG },
        miniflare: {
          bindings: {
            TEST_MIGRATIONS: migrations,
            TEST_API_MIGRATIONS: apiMigrations,
            ISSUER_SIGNING_KEY: JSON.stringify(primary.private),
            TEST_STANDBY_KEY: JSON.stringify(standby.private),
            EMAIL_SUB_KEY: randomBytes(32).toString('base64'),
            EMAIL_CODE_KEY: randomBytes(32).toString('base64'),
            EMAIL_RL_KEY: randomBytes(32).toString('base64'),
            SENDGRID_API_KEY: `SG.${randomBytes(16).toString('base64url')}.${randomBytes(24).toString('base64url')}`,
            // DirectoryRpc's staff check (D275): the admin application the tests' Access JWTs are minted for.
            ADMIN_ACCESS_TEAM_DOMAIN: 'hana-admin-test.cloudflareaccess.com',
            ADMIN_ACCESS_AUD: 'cd'.repeat(32),
            ADMIN_STAFF_EMAILS: JSON.stringify(['staff@hana.example', 'other-staff@hana.example', 'budget@hana.example', 'budget2@hana.example']),
          },
          d1Databases: { DB: 'hana-id-email-issuer-test', API_TEST_DB: API_DB_ID },
          workers: [
            {
              // The API Worker, serving IssuerRpc on its own D1 (the database API_TEST_DB names). Nothing else of it
              // runs here: no route reaches its fetch and its NEAR RPC is an invalid host.
              name: TEST_MANIFEST.cloudflare.workerName,
              modules: true,
              scriptPath: apiScript,
              compatibilityDate: COMPATIBILITY_DATE,
              compatibilityFlags: ['nodejs_compat'],
              d1Databases: { DB: API_DB_ID },
              bindings: { ENV_NAME: TEST_MANIFEST.name, NEAR_RPC: 'https://rpc.test.invalid', SIGNER_ACCOUNT: TEST_MANIFEST.signer },
            },
          ],
        },
      }),
    ],
    test: {
      include: ['test/**/*.test.ts'],
      // Some tests make 100+ requests (domain caps, drains): 5 s isn't enough under a loaded `pnpm -r test`.
      testTimeout: 30_000,
      setupFiles: ['./test/apply-migrations.ts'],
      onConsoleLog: (log: string) => (process.env.LOG || !log.startsWith('{"level"') ? undefined : false),
    },
  };
});
