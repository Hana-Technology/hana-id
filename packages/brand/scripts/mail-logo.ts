// Draws the mail logo (src/mail-logo.ts, D685): Hana's mark and wordmark from logo/, on a white plate so it reads on
// light, dark and inverted mail backgrounds, at 2x for retina. Run after a change to the mark or the wordmark:
//
//   pnpm --filter @hana-id/brand mail-logo
//
// Renders with the Playwright Chromium the e2e package installs, writes mail/hana-mail-logo.png and rewrites
// src/mail-logo.ts (the bytes as base64, their sha256 in the path, so a new logo gets a new URL). Mails already sent
// keep the old URL: the files Worker serves only the current one, and an old mail shows its "Hana ID" fallback.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, '..', '..', 'apps', 'e2e', 'package.json'));
const { chromium } = require('@playwright/test') as typeof import('@playwright/test');

/** CSS pixels: the plate, and the mark and wordmark inside it (the auth pages' bar: a 28 px mark, a 66 × 13 wordmark). */
export const WIDTH = 120;
export const HEIGHT = 40;

const mark = readFileSync(join(root, 'logo', 'hana-mark.svg'), 'utf8').replace('<svg ', '<svg style="width:28px;height:28px;display:block" ');
const wordmark = readFileSync(join(root, 'logo', 'hana-wordmark.svg'), 'utf8').replace('<svg ', '<svg style="width:66px;height:13px;display:block;color:#16073a" ');
const page = `<!doctype html><html><body style="margin:0;background:transparent">
<div id="logo" style="width:${WIDTH}px;height:${HEIGHT}px;box-sizing:border-box;background:#ffffff;border-radius:10px;display:flex;align-items:center;gap:9px;padding:0 6px">${mark}${wordmark}</div>
</body></html>`;

const browser = await chromium.launch();
const p = await browser.newPage({ deviceScaleFactor: 2, viewport: { width: WIDTH, height: HEIGHT } });
await p.setContent(page);
const png = await p.locator('#logo').screenshot({ omitBackground: true });
await browser.close();

const sha = createHash('sha256').update(png).digest('hex');
writeFileSync(join(root, 'mail', 'hana-mail-logo.png'), png);
writeFileSync(
  join(root, 'src', 'mail-logo.ts'),
  `// Generated by scripts/mail-logo.ts from logo/hana-mark.svg and logo/hana-wordmark.svg (D685): never edit by hand.
// The mail logo: Hana's mark and wordmark on a white plate, ${WIDTH * 2} × ${HEIGHT * 2} px, shown at ${WIDTH} × ${HEIGHT}. The files Worker serves these
// bytes at MAIL_LOGO_PATH on the env's files origin; the path names their sha256, so it changes with the image.

export const MAIL_LOGO_WIDTH = ${WIDTH};
export const MAIL_LOGO_HEIGHT = ${HEIGHT};
export const MAIL_LOGO_SHA256 = '${sha}';
export const MAIL_LOGO_PATH = '/brand/hana-mail-logo-${sha.slice(0, 16)}.png';
export const MAIL_LOGO_PNG_BASE64 = '${png.toString('base64')}';
`,
);
console.log(`hana-mail-logo.png: ${png.length} bytes, sha256 ${sha}`);
