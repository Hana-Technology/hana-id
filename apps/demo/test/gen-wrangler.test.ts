import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { COMPATIBILITY_DATE } from '../../api/scripts/gen-wrangler.ts';
import { pageCsp } from '../src/csp.ts';
import { CONFIG_FILE, demoPlacement, demoWranglerConfig, writeDemoWranglerConfig } from '../scripts/gen-wrangler.ts';
import { CONFIG, MANIFEST, variant } from './fixtures.ts';

const dirs: string[] = [];
const tmp = (): string => {
  const d = mkdtempSync(join(tmpdir(), 'hana-demo-wrangler-'));
  dirs.push(d);
  return d;
};
afterEach(() => {
  for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true });
});

describe('demoPlacement', () => {
  it("names the Worker hana-id-demo-<env> on the API's workers.dev subdomain", () => {
    expect(demoPlacement(MANIFEST)).toEqual({ name: 'hana-id-demo-sandbox-dev', origin: 'https://hana-id-demo-sandbox-dev.tingtc.workers.dev' });
    expect(demoPlacement(variant({ name: 'sandbox-x', apiUrl: 'https://api-x.other.workers.dev' })).origin).toBe('https://hana-id-demo-sandbox-x.other.workers.dev');
  });

  it('refuses envs that are not testnet dev envs, and an API on a custom domain', () => {
    const prod = variant({ name: 'prod', apiUrl: 'https://api.hana-api.example', vaultOrigin: 'https://vault.hana-vault.example', authOrigin: 'https://auth.hana-auth.example' });
    expect(() => demoPlacement(prod)).toThrow(/sandbox\*\/local\* envs only/u);
    expect(() => demoPlacement(variant({ apiUrl: 'https://api.hana.example' }))).toThrow(/not on workers.dev/u);
    expect(() => demoPlacement(variant({ vaultOrigin: 'https://hana-id-demo-sandbox-dev.tingtc.workers.dev' }))).toThrow(/already one of the env's Hana origins/u);
  });
});

describe('demoWranglerConfig', () => {
  it('serves dist/ through the Worker on workers.dev only, with the page CSP', () => {
    expect(demoWranglerConfig(MANIFEST, CONFIG)).toEqual({
      $schema: 'node_modules/wrangler/config-schema.json',
      name: 'hana-id-demo-sandbox-dev',
      main: 'worker/index.ts',
      compatibility_date: COMPATIBILITY_DATE,
      workers_dev: true,
      preview_urls: false,
      vars: { DEMO_ORIGIN: 'https://hana-id-demo-sandbox-dev.tingtc.workers.dev', CSP: pageCsp(CONFIG) },
      assets: { directory: './dist', binding: 'ASSETS', run_worker_first: true, html_handling: 'none', not_found_handling: 'none' },
    });
  });

  it("refuses a configuration made for another env or another vault (the page's CSP would block its vault)", () => {
    expect(() => demoWranglerConfig(variant({ name: 'sandbox-x' }), CONFIG)).toThrow(/is for sandbox-dev, not sandbox-x/u);
    expect(() => demoWranglerConfig(variant({ vaultOrigin: 'https://other-vault.tingtc.workers.dev' }), CONFIG)).toThrow(/vault/u);
  });
});

describe('writeDemoWranglerConfig', () => {
  it('writes wrangler.jsonc for the env and key the variables select', () => {
    const dir = tmp();
    const loaded: string[] = [];
    const out = writeDemoWranglerConfig(
      { HANA_DEMO_ENV: 'sandbox-dev', HANA_DEMO_PUBLISHABLE_KEY: 'pk_test_2222222222222222' },
      {
        dir,
        loadManifest: (name) => {
          loaded.push(name);
          return MANIFEST;
        },
      },
    );
    expect(loaded).toEqual(['sandbox-dev']);
    expect(out.path).toBe(join(dir, CONFIG_FILE));
    expect(out.origin).toBe('https://hana-id-demo-sandbox-dev.tingtc.workers.dev');
    expect(out.config.publishableKey).toBe('pk_test_2222222222222222');
    const text = readFileSync(out.path, 'utf8');
    expect(text.startsWith('// Generated by apps/demo/scripts/gen-wrangler.ts from envs/sandbox-dev.json')).toBe(true);
    const json = JSON.parse(text.slice(text.indexOf('\n') + 1)) as { name: string; vars: Record<string, string> };
    expect(json.name).toBe('hana-id-demo-sandbox-dev');
    // The publishable key is baked into the page, not the Worker.
    expect(text).not.toContain('pk_test_');
  });
});
