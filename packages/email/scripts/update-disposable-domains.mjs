#!/usr/bin/env node
// Re-vendors the disposable-address domain list into src/disposable-domains.ts from one pinned commit of
// https://github.com/disposable-email-domains/disposable-email-domains (CC0 1.0), file disposable_email_blocklist.conf.
// Updates go through a PR and are reviewed like code (docs/email-login-spec.md "Rate limits and abuse"). Pick a commit
// at least 7 days old (the workspace's minimumReleaseAge rule for packages applies to this data too), then:
//
//   node packages/email/scripts/update-disposable-domains.mjs <40-hex commit>
//   node packages/email/scripts/update-disposable-domains.mjs <commit> --from <file> --date <ISO date>   # offline
//
// It refuses a commit younger than 7 days, a list that holds a Google-hosted domain (or a parent of one,
// scripts/protected-domains.mjs), a line that isn't a lowercase LDH domain with a dot, or duplicates. Network use is
// here only, never in tests.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { protectedConflicts } from './protected-domains.mjs';

const REPO = 'disposable-email-domains/disposable-email-domains';
const FILE = 'disposable_email_blocklist.conf';
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'disposable-domains.ts');
const MIN_AGE_MS = 7 * 24 * 60 * 60 * 1000;

const args = process.argv.slice(2);
const commit = args[0];
const opt = (name) => {
  const i = args.indexOf(name);
  return i === -1 ? undefined : args[i + 1];
};
if (!commit || !/^[0-9a-f]{40}$/.test(commit)) {
  console.error('usage: update-disposable-domains.mjs <40-hex commit> [--from <file> --date <ISO date>]');
  process.exit(2);
}

async function fetchText(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

const from = opt('--from');
const text = from ? readFileSync(from, 'utf8') : await fetchText(`https://raw.githubusercontent.com/${REPO}/${commit}/${FILE}`);
let committedAt = opt('--date');
if (!committedAt) {
  const meta = JSON.parse(await fetchText(`https://api.github.com/repos/${REPO}/commits/${commit}`));
  committedAt = meta.commit.committer.date;
}
const committedMs = Date.parse(committedAt);
if (!Number.isFinite(committedMs)) throw new Error(`not a date: ${committedAt}`);
if (Date.now() - committedMs < MIN_AGE_MS) {
  throw new Error(`commit ${commit} is from ${committedAt}: younger than 7 days, pick an older one`);
}

if (!text.endsWith('\n') || text.includes('\r')) throw new Error('expected LF-terminated lines');
const domains = text.slice(0, -1).split('\n');
const LDH = /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)+$/;
const seen = new Set();
for (const d of domains) {
  if (!LDH.test(d)) throw new Error(`not a lowercase LDH domain with a dot: ${JSON.stringify(d)}`);
  if (seen.has(d)) throw new Error(`duplicate: ${d}`);
  seen.add(d);
}
const conflicts = protectedConflicts(seen);
if (conflicts.length > 0) throw new Error(`refusing a list that blocks a Google-hosted domain: ${conflicts.join(', ')}`);

const sha256 = createHash('sha256').update(text, 'utf8').digest('hex');
const out = `// GENERATED by scripts/update-disposable-domains.mjs: do not edit by hand. Updates go through a reviewed PR.
//
// Disposable-address domains blocked at email login \`start\` (\`400 email_domain_not_allowed\`, D123, D157).
// Source: https://github.com/${REPO}, file ${FILE}
// Pinned commit: ${commit} (${committedAt})
// Upstream file sha256: ${sha256}
// Entries: ${domains.length}. Licence: CC0 1.0 Universal (public domain dedication).
// Never holds a Google-hosted domain (test/disposable.test.ts guards it).

export const DISPOSABLE_DOMAINS_SOURCE = Object.freeze({
  repository: 'https://github.com/${REPO}',
  file: '${FILE}',
  commit: '${commit}',
  committedAt: '${committedAt}',
  sha256: '${sha256}',
  count: ${domains.length},
  license: 'CC0-1.0',
});

/** The upstream file byte for byte (one domain per line, LF-terminated). */
export const DISPOSABLE_DOMAINS_TEXT = \`${text}\`;
`;
writeFileSync(OUT, out);
console.log(`wrote ${OUT}: ${domains.length} domains at ${commit}`);
