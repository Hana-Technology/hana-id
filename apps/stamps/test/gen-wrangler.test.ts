import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { COMPATIBILITY_DATE } from '../../api/scripts/gen-wrangler.ts';
import { pageCsp } from '../src/csp.ts';
import { CONFIG_FILE, stampsPlacement, stampsWranglerConfig, writeStampsWranglerConfig } from '../scripts/gen-wrangler.ts';
import { CONFIG, MANIFEST, PK, variant, withStamps } from './fixtures.ts';
import { customDomainManifest } from '../../../packages/env/src/custom-domain.fixture.ts';

const dirs: string[] = [];
const tmp = (): string => {
  const d = mkdtempSync(join(tmpdir(), 'hana-stamps-wrangler-'));
  dirs.push(d);
  return d;
};
afterEach(() => {
  for (const d of dirs.splice(0)) rmSync(d, { recursive: true, force: true });
});

describe('stampsPlacement', () => {
  it("names the Worker hana-id-stamps-<env> on the API's workers.dev subdomain", () => {
    expect(stampsPlacement(MANIFEST)).toEqual({ name: 'hana-id-stamps-sandbox-dev', origin: 'https://hana-id-stamps-sandbox-dev.tingtc.workers.dev', target: { workers_dev: true, preview_urls: false } });
  });

  it('refuses envs that are not testnet dev envs, and an API on a custom domain without HANA_STAMPS_ORIGIN', () => {
    expect(() => stampsPlacement(variant({ name: 'prod', apiUrl: 'https://api.hana-api.example', vaultOrigin: 'https://vault.hana-vault.example', authOrigin: 'https://auth.hana-auth.example' }))).toThrow(/sandbox\*\/local\* envs only/u);
    expect(() => stampsPlacement(variant({ apiUrl: 'https://api.hana.example' }))).toThrow(/not on workers.dev/u);
    expect(() => stampsPlacement(variant({ vaultOrigin: 'https://hana-id-stamps-sandbox-dev.tingtc.workers.dev' }))).toThrow(/already one of the env's Journear origins/u);
    const m = customDomainManifest();
    expect(stampsPlacement(m, 'https://stamps.id-dev.hanawallet.io').origin).toBe('https://stamps.id-dev.hanawallet.io');
    expect(() => stampsPlacement(m)).toThrow(/set HANA_STAMPS_ORIGIN/u);
  });
});

describe('stampsWranglerConfig', () => {
  it('serves dist/ through the Worker on workers.dev only, with the page CSP', () => {
    expect(stampsWranglerConfig(MANIFEST, CONFIG)).toEqual({
      $schema: 'node_modules/wrangler/config-schema.json',
      name: 'hana-id-stamps-sandbox-dev',
      main: 'worker/index.ts',
      compatibility_date: COMPATIBILITY_DATE,
      workers_dev: true,
      preview_urls: false,
      vars: { STAMPS_ORIGIN: 'https://hana-id-stamps-sandbox-dev.tingtc.workers.dev', CSP: pageCsp(CONFIG) },
      assets: { directory: './dist', binding: 'ASSETS', run_worker_first: true, html_handling: 'none', not_found_handling: 'none' },
    });
  });

  it('refuses a configuration made for another env or another vault', () => {
    expect(() => stampsWranglerConfig(variant({ name: 'sandbox-x' }), CONFIG)).toThrow(/is for sandbox-dev, not sandbox-x/u);
    expect(() => stampsWranglerConfig(variant({ vaultOrigin: 'https://other-vault.tingtc.workers.dev' }), CONFIG)).toThrow(/vault/u);
  });
});

describe('writeStampsWranglerConfig', () => {
  it('writes wrangler.jsonc for the env and key the variables select, without the key', () => {
    const dir = tmp();
    const out = writeStampsWranglerConfig({ HANA_STAMPS_PUBLISHABLE_KEY: PK }, { dir, loadManifest: () => MANIFEST });
    expect(out.path).toBe(join(dir, CONFIG_FILE));
    expect(out.origin).toBe('https://hana-id-stamps-sandbox-dev.tingtc.workers.dev');
    const text = readFileSync(out.path, 'utf8');
    expect(text.startsWith('// Generated by apps/stamps/scripts/gen-wrangler.ts from envs/sandbox-dev.json')).toBe(true);
    expect(text).not.toContain('pk_test_');
  });

  it('refuses without the key, and for an env whose manifest has no stamps contract', () => {
    expect(() => writeStampsWranglerConfig({}, { dir: tmp(), loadManifest: () => MANIFEST })).toThrow(/HANA_STAMPS_PUBLISHABLE_KEY is required/u);
    expect(() => writeStampsWranglerConfig({ HANA_STAMPS_PUBLISHABLE_KEY: PK }, { dir: tmp(), loadManifest: () => withStamps(MANIFEST, undefined) })).toThrow(/sets no near\.demoStamps/u);
  });
});
