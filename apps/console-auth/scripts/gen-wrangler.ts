// Generates apps/console-auth/wrangler.jsonc (gitignored, like every generated config) from envs/<env>.json's `console`
// block (docs/batch-c-spec.md "Bindings": console-auth binds `CONSOLE` → `AuthHandler`, has `AUTH_ORIGIN`, and no
// secret, D1 or Hyperdrive).
//
//   pnpm --filter @hana-id/console-auth gen <env>
//
// Deploy after the console Worker (the service binding needs it): `pnpm --filter @hana-id/console-auth run deploy`.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { type Manifest, loadEnv } from '@hana-id/env';
import { COMPATIBILITY_DATE, placement } from '../../console/scripts/gen-wrangler.ts';

const appDir = join(dirname(fileURLToPath(import.meta.url)), '..');

export function wranglerConfig(m: Manifest): Record<string, unknown> {
  const c = m.console;
  if (!c) throw new Error(`envs/${m.name}.json has no console block`);
  return {
    $schema: 'node_modules/wrangler/config-schema.json',
    name: c.authWorkerName,
    main: 'src/index.ts',
    compatibility_date: COMPATIBILITY_DATE,
    ...placement(m, 'console.authOrigin', c.authOrigin, c.authWorkerName),
    // The Worker's own log lines only: the platform's invocation records would carry `/callback`'s `code` and `state`.
    observability: { enabled: true, logs: { invocation_logs: false } },
    vars: { AUTH_ORIGIN: c.authOrigin },
    services: [{ binding: 'CONSOLE', service: c.workerName, entrypoint: 'AuthHandler' }],
  };
}

export function main(argv: string[], opts: { dir?: string; loadManifest?: (name: string) => Manifest } = {}): void {
  const envName = argv.find((a) => !a.startsWith('--'));
  if (!envName) {
    console.error('usage: gen-wrangler <env>');
    process.exit(2);
  }
  const manifest = (opts.loadManifest ?? loadEnv)(envName);
  const path = join(opts.dir ?? appDir, 'wrangler.jsonc');
  const header = `// Generated by apps/console-auth/scripts/gen-wrangler.ts from envs/${manifest.name}.json: edit the manifest, not this file.\n`;
  writeFileSync(path, header + JSON.stringify(wranglerConfig(manifest), null, 2) + '\n');
  console.log(`wrote ${path} (env ${manifest.name}, worker ${manifest.console!.authWorkerName}, served on ${manifest.console!.authOrigin})`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main(process.argv.slice(2));
