// Draws the mail logo (src/mail-logo.ts, D685 as amended by D765): the Journear lockup (mark, wordmark and
// "PASSPORT") from logo/journear-lockup.svg, on a light plate so it reads on light, dark and inverted mail backgrounds,
// at 2x for retina. Run after a change to the lockup:
//
//   pnpm --filter @hana-id/brand mail-logo
//
// Renders with the Playwright Chromium the e2e package installs, with the shipped Archivo 700 for the lockup's live
// "PASSPORT" text (so the result doesn't depend on the machine's fonts), writes mail/journear-mail-logo.png and
// rewrites src/mail-logo.ts (the bytes as base64, their sha256 in the path, so a new logo gets a new URL). Mails
// already sent keep the old URL: the files Worker serves only the current one, and an old mail shows its alt text.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, '..', '..', 'apps', 'e2e', 'package.json'));
const { chromium } = require('@playwright/test') as typeof import('@playwright/test');

/**
 * CSS pixels: the plate, and the lockup inside it. The lockup is 132 px wide (the logo rules: at least 120 px), and the
 * plate leaves about the chevron's height (7 px at this size) of clear space around it.
 */
export const WIDTH = 148;
export const HEIGHT = 44;
const LOCKUP_WIDTH = 132;
/** The lockup's own aspect (its viewBox, 561 × 128). */
const LOCKUP_HEIGHT = Math.round((LOCKUP_WIDTH * 128) / 561);

const font = readFileSync(join(root, 'fonts', 'archivo-700.woff2')).toString('base64');
const lockup = readFileSync(join(root, 'logo', 'journear-lockup.svg'), 'utf8').replace('<svg ', `<svg style="width:${LOCKUP_WIDTH}px;height:${LOCKUP_HEIGHT}px;display:block" `);
const page = `<!doctype html><html><head><style>@font-face{font-family:Archivo;font-weight:700;src:url(data:font/woff2;base64,${font}) format("woff2")}</style></head><body style="margin:0;background:transparent">
<div id="logo" style="width:${WIDTH}px;height:${HEIGHT}px;box-sizing:border-box;background:#fcfdfd;border-radius:8px;display:flex;align-items:center;justify-content:center">${lockup}</div>
</body></html>`;

const browser = await chromium.launch();
const p = await browser.newPage({ deviceScaleFactor: 2, viewport: { width: WIDTH, height: HEIGHT } });
await p.setContent(page);
await p.evaluate(async () => {
  await document.fonts.load('700 22px Archivo');
  await document.fonts.ready;
});
if (!(await p.evaluate(() => document.fonts.check('700 22px Archivo')))) throw new Error('Archivo 700 did not load: the lockup would be drawn in a fallback face');
const png = await p.locator('#logo').screenshot({ omitBackground: true });
await browser.close();

const sha = createHash('sha256').update(png).digest('hex');
writeFileSync(join(root, 'mail', 'journear-mail-logo.png'), png);
writeFileSync(
  join(root, 'src', 'mail-logo.ts'),
  `// Generated by scripts/mail-logo.ts from logo/journear-lockup.svg (D685, D765): never edit by hand.
// The mail logo: the Journear lockup on a light plate, ${WIDTH * 2} × ${HEIGHT * 2} px, shown at ${WIDTH} × ${HEIGHT}. The files Worker serves these
// bytes at MAIL_LOGO_PATH on the env's files origin; the path names their sha256, so it changes with the image.

export const MAIL_LOGO_WIDTH = ${WIDTH};
export const MAIL_LOGO_HEIGHT = ${HEIGHT};
export const MAIL_LOGO_SHA256 = '${sha}';
export const MAIL_LOGO_PATH = '/brand/journear-mail-logo-${sha.slice(0, 16)}.png';
export const MAIL_LOGO_PNG_BASE64 = '${png.toString('base64')}';
`,
);
console.log(`journear-mail-logo.png: ${png.length} bytes, sha256 ${sha}`);
