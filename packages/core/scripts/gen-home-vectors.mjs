#!/usr/bin/env node
// Writes test/vectors/home-v1.json: worked examples of Hana Home's byte layouts (docs/hana-home-spec.md): the identity
// nonce, the message each API call signs, the x-hana-home header and the two consent payloads inside a vault message.
// An independent implementation (node:crypto and Buffer only) that src/home.ts, src/layouts.ts and apps/api's identity
// verifier must agree with byte for byte (test/home.test.ts, apps/api/test/home-identity.test.ts). Test-only keys.
//
//   node packages/core/scripts/gen-home-vectors.mjs

import { createHash, createPrivateKey, createPublicKey, sign } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'test', 'vectors', 'home-v1.json');

const SIGNER = 'hana-signer.testnet';
const APP_ID = 'app_0123456789abcdef';
const PARENT = 'https://partner.example';
const EXPIRES = 1_800_000_900_000;
const SEED = Buffer.alloc(32, 7);
const SALT = Buffer.from(Array.from({ length: 32 }, (_, i) => 0x40 + i));
const CONSENT_ID = Buffer.from(Array.from({ length: 16 }, (_, i) => 0xc0 + i));
const POLICY_ID = Buffer.from(Array.from({ length: 32 }, (_, i) => 0x10 + i));
const SHARE_ID = Buffer.from(Array.from({ length: 16 }, (_, i) => i + 1));

const hex = (b) => Buffer.from(b).toString('hex');
const b64url = (b) => Buffer.from(b).toString('base64url');
const sha256 = (b) => createHash('sha256').update(b).digest();
const ascii = (s) => Buffer.from(s, 'utf8');
const u32 = (n) => {
  const b = Buffer.alloc(4);
  b.writeUInt32LE(n);
  return b;
};
const u64 = (n) => {
  const b = Buffer.alloc(8);
  b.writeBigUInt64LE(BigInt(n));
  return b;
};
const str = (s) => Buffer.concat([u32(Buffer.byteLength(s, 'utf8')), ascii(s)]);
const concat = (parts) => Buffer.concat(parts.map(([, b]) => b));
const seedKey = (seed) => createPrivateKey({ key: Buffer.concat([Buffer.from('302e020100300506032b657004220420', 'hex'), seed]), format: 'der', type: 'pkcs8' });
const PK = Buffer.from(createPublicKey(seedKey(SEED)).export({ format: 'jwk' }).x, 'base64url');
const example = (title, parts, extra = {}) => ({ title, parts: parts.map(([label, b]) => [label, hex(b)]), preimage_hex: hex(concat(parts)), ...extra });

// ---- nonce ----
const nonceParts = (signer, key, expiresAtMs, salt) => [
  ['"hana-id/home/v1"', ascii('hana-id/home/v1')],
  [`borsh(signer "${signer}")`, str(signer)],
  ['hk_pub (32)', key],
  [`expiresAtMs ${expiresAtMs} (u64 LE)`, u64(expiresAtMs)],
  ['salt (32)', salt],
];
const nonceExample = (title, signer, key, expiresAtMs, salt) => {
  const parts = nonceParts(signer, key, expiresAtMs, salt);
  return example(title, parts, { input: { signer, pk_hex: hex(key), expiresAtMs, salt_hex: hex(salt) }, nonce: b64url(sha256(concat(parts))) });
};

// ---- message ----
const messageParts = (signer, counter, method, path, body) => {
  const inner = Buffer.concat([str(method), str(path), body]);
  return [
    ['"hana-id-home-v1:"', ascii('hana-id-home-v1:')],
    [`borsh(signer "${signer}")`, str(signer)],
    [`counter ${counter} (u64 LE)`, u64(counter)],
    ['sha256(borsh(method) ‖ borsh(path) ‖ body)', sha256(inner)],
  ];
};
const messageExample = (title, counter, method, path, body) => {
  const parts = messageParts(SIGNER, counter, method, path, body);
  return example(title, parts, { input: { signer: SIGNER, counter, method, path, body_hex: hex(body) }, signature_seed7_hex: hex(sign(null, concat(parts), seedKey(SEED))) });
};

const POST_BODY = Buffer.from('{"consentId":"wMHCw8TFxsfIycrLzM3Ozw"}', 'utf8');

// ---- header: the fields in the order the page writes them, around a placeholder token ----
const JWT = 'test-header.test-payload.test-signature';
const headerMessage = concat(messageParts(SIGNER, 1, 'GET', '/v1/home/apps', Buffer.alloc(0)));
const sig = sign(null, headerMessage, seedKey(SEED));
const headerFields = { jwt: JWT, key: b64url(PK), expiresAtMs: EXPIRES, salt: b64url(SALT), counter: 1, sig: b64url(sig) };

// ---- consent payloads inside a vault message (layouts.ts vaultMessage) ----
const consentRegister = Buffer.concat([ascii('consent'), CONSENT_ID, POLICY_ID, u64(EXPIRES), str(PARENT)]);
const consentRevoke = Buffer.concat([ascii('consent-revoke'), CONSENT_ID]);
const vault = (title, shareId, counter, payload) => {
  const parts = [
    ['"hana-id-vault-v1:"', ascii('hana-id-vault-v1:')],
    [`borsh(signer "${SIGNER}")`, str(SIGNER)],
    [`borsh(appId "${APP_ID}")`, str(APP_ID)],
    ['shareId (16)', shareId],
    [`counter ${counter} (u64 LE)`, u64(counter)],
    ['sha256(payload)', sha256(payload)],
  ];
  return example(title, parts, { input: { shareId_hex: hex(shareId), counter, payload_hex: hex(payload) } });
};

const fixture = {
  _comment: 'Generated by packages/core/scripts/gen-home-vectors.mjs (independent of src/home.ts). Test-only values.',
  signer: SIGNER,
  app_id: APP_ID,
  parent_origin: PARENT,
  seed7_hex: hex(SEED),
  pk_hex: hex(PK),
  nonces: {
    basic: nonceExample('Home nonce: hk_pub of seed [7; 32], salt 0x40..5f, expiresAtMs 1800000900000', SIGNER, PK, EXPIRES, SALT),
    other_signer: nonceExample('Same fields, another signer account: another nonce', 'hana-signer-other.testnet', PK, EXPIRES, SALT),
  },
  messages: {
    get: messageExample('homeMessage: GET /v1/home/apps, counter 1, empty body', 1, 'GET', '/v1/home/apps', Buffer.alloc(0)),
    get_query: messageExample('homeMessage: the query is part of the path signed', 2, 'GET', '/v1/home/devices?scopeId=s1&cursor=abc', Buffer.alloc(0)),
    post: messageExample('homeMessage: POST with a body', 3, 'POST', '/v1/home/consents/revoke', POST_BODY),
  },
  header: {
    fields_input: { jwt: JWT, pk_hex: hex(PK), expiresAtMs: EXPIRES, salt_hex: hex(SALT), counter: 1, sig_hex: hex(sig) },
    // The header value is b64url of this JSON (the test encodes it the same way: the long opaque value would only trip the secret scanner).
    json: JSON.stringify(headerFields),
  },
  consent: {
    input: { consentId_hex: hex(CONSENT_ID), policyId_hex: hex(POLICY_ID), expiresAtMs: EXPIRES, parentOrigin: PARENT },
    register_payload_hex: hex(consentRegister),
    revoke_payload_hex: hex(consentRevoke),
    vault_message_register: vault('Vault message, register a consent: shareId 01..10, counter 9', SHARE_ID, 9, consentRegister),
    vault_message_register_none_mode: vault("Vault message, register a consent in 'none' mode: shareId 16 zero bytes, counter 0", Buffer.alloc(16), 0, consentRegister),
    vault_message_revoke: vault('Vault message, device revoke: shareId 01..10, counter 10', SHARE_ID, 10, consentRevoke),
  },
};
writeFileSync(OUT, `${JSON.stringify(fixture, null, 2)}\n`);
console.log(`wrote ${OUT}`);
