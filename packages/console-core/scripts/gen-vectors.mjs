#!/usr/bin/env node
// Generates test/vectors.json: an independent Node implementation (node:crypto, Buffer, its own canonical JSON) of
// the console layouts in docs/batch-c-spec.md "Nonce and digest layouts", in the style of
// contracts/hana-signer/scripts/gen-fixtures.mjs. The TypeScript in src/ must agree with it byte for byte
// (test/layouts.test.ts); the owner-action and client-proof layouts are checked against the contract's own
// test_fixture.json instead. Keys and randoms here are fixed test values, never real secrets.
//
//   node packages/console-core/scripts/gen-vectors.mjs        # writes test/vectors.json
//
// test/layouts.test.ts also imports buildVectors() and checks that the committed file is current.
import { createHash, createHmac } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'test', 'vectors.json');

const sha256 = (buf) => createHash('sha256').update(buf).digest();
const hmac = (key, buf) => createHmac('sha256', key).update(buf).digest();
const ascii = (s) => Buffer.from(s, 'utf8');
const u32 = (n) => { const b = Buffer.alloc(4); b.writeUInt32LE(n); return b; };
const u64 = (n) => { const b = Buffer.alloc(8); b.writeBigUInt64LE(BigInt(n)); return b; };
const str = (s) => { const bytes = Buffer.from(s, 'utf8'); return Buffer.concat([u32(bytes.length), bytes]); };
const vec = (list) => Buffer.concat([u32(list.length), ...list.map(str)]);
const b64url = (buf) => Buffer.from(buf).toString('base64url');
const hexOf = (buf) => Buffer.from(buf).toString('hex');
const byteSort = (list) => [...list].sort((a, b) => Buffer.compare(Buffer.from(a, 'utf8'), Buffer.from(b, 'utf8')));

// Canonical JSON (RFC 8785) written out separately: sorted keys by UTF-16 code units, ES number formatting.
function jcs(v) {
  if (v === null || typeof v === 'boolean' || typeof v === 'number') return JSON.stringify(v);
  if (typeof v === 'string') return JSON.stringify(v);
  if (Array.isArray(v)) return '[' + v.map(jcs).join(',') + ']';
  const keys = Object.keys(v).sort((a, b) => {
    for (let i = 0; i < Math.min(a.length, b.length); i++) {
      const d = a.charCodeAt(i) - b.charCodeAt(i);
      if (d !== 0) return d;
    }
    return a.length - b.length;
  });
  return '{' + keys.map((k) => JSON.stringify(k) + ':' + jcs(v[k])).join(',') + '}';
}

const SIGNER = 'hana-id-signer-dev1.testnet';
const LINK_KEY = Buffer.alloc(32, 0x11);
const INVITE_KEY = Buffer.alloc(32, 0x22);
const USER_ID_KEY = Buffer.alloc(32, 0x33);
const SESSION_HASH = sha256(Buffer.alloc(32, 0x44)); // sha256 of a session cookie value
const LOGIN_RANDOM = Buffer.alloc(32, 0x55);
const POLICY_ID = 'a1'.repeat(32);

export function buildVectors() {
  const loginPre = Buffer.concat([ascii('hana-console/login/v1'), LOGIN_RANDOM]);

  const action = { v: 1, env: 'sandbox-dev', org_id: 'org_7Yk3Qm2Pz9VxR4tLs', kind: 'member.invite', params: { email: 'new@partner.example', role: 'viewer' } };
  const stepUpPre = Buffer.concat([ascii('hana-console/step-up/v1'), SESSION_HASH, sha256(ascii(jcs(action)))]);

  // Inputs given unsorted; the layout sorts by UTF-8 byte order.
  const add = ['https://xn--bcher-kva.example', 'https://app.partner.example', 'http://localhost:5173'];
  const remove = ['https://old.partner.example'];
  const originPre = Buffer.concat([ascii('hana-id/origin-change/v1'), str(SIGNER), str('app_3vQb7Wk2Lm9Xp4Rz'), vec(byteSort(add)), vec(byteSort(remove)), u64(7)]);
  const originAddOnlyPre = Buffer.concat([ascii('hana-id/origin-change/v1'), str(SIGNER), str('app_3vQb7Wk2Lm9Xp4Rz'), vec(['https://app.partner.example']), vec([]), u64(0)]);

  const policyPre = Buffer.concat([ascii('hana-id/settings-change/v1'), str(SIGNER), str('app_3vQb7Wk2Lm9Xp4Rz'), str('policy_set'), Buffer.from(POLICY_ID, 'hex'), u64(3)]);
  const rawPre = Buffer.concat([ascii('hana-id/settings-change/v1'), str(SIGNER), str('app_3vQb7Wk2Lm9Xp4Rz'), str('raw_sign_on'), Buffer.alloc(32), u64(4)]);

  const cancel = hmac(LINK_KEY, Buffer.concat([ascii('hana-id/cancel-link/v1'), str('gc_5Tn8Wq1Ys6Hb3Kd')]));
  const invite = hmac(INVITE_KEY, Buffer.concat([ascii('hana-console/invite/v1'), str('inv_9Jc4Vx7Rm2Lq8Np')]));
  const grant = hmac(LINK_KEY, Buffer.concat([ascii('hana-console/owner-grant-cancel/v1'), str('og_2Hs6Dp9Fw3Zt5Gy')]));

  const uidOf = (scope, provider, sub) => hmac(USER_ID_KEY, Buffer.concat([ascii('hana-id/uid/v1'), str(scope), str(provider), str(sub)])).subarray(0, 16);

  return {
    _comment: 'Generated by packages/console-core/scripts/gen-vectors.mjs (independent implementation). Do not edit.',
    inputs: {
      signer: SIGNER,
      link_key_hex: hexOf(LINK_KEY),
      invite_key_hex: hexOf(INVITE_KEY),
      user_id_key_hex: hexOf(USER_ID_KEY),
      session_hash_hex: hexOf(SESSION_HASH),
      login_random_hex: hexOf(LOGIN_RANDOM),
      policy_id: POLICY_ID,
    },
    console_login: { preimage_hex: hexOf(loginPre), nonce: b64url(sha256(loginPre)) },
    step_up: { action, jcs: jcs(action), preimage_hex: hexOf(stepUpPre), digest_hex: hexOf(sha256(stepUpPre)), nonce: b64url(sha256(stepUpPre)) },
    origin_change: { app_id: 'app_3vQb7Wk2Lm9Xp4Rz', add, remove, origins_version: 7, preimage_hex: hexOf(originPre), nonce: b64url(sha256(originPre)) },
    origin_change_add_only: { app_id: 'app_3vQb7Wk2Lm9Xp4Rz', add: ['https://app.partner.example'], remove: [], origins_version: 0, preimage_hex: hexOf(originAddOnlyPre), nonce: b64url(sha256(originAddOnlyPre)) },
    settings_policy_set: { app_id: 'app_3vQb7Wk2Lm9Xp4Rz', settings_version: 3, preimage_hex: hexOf(policyPre), nonce: b64url(sha256(policyPre)) },
    settings_raw_sign_on: { app_id: 'app_3vQb7Wk2Lm9Xp4Rz', settings_version: 4, preimage_hex: hexOf(rawPre), nonce: b64url(sha256(rawPre)) },
    cancel_link: { change_id: 'gc_5Tn8Wq1Ys6Hb3Kd', token: b64url(cancel), token_hash_hex: hexOf(sha256(cancel)) },
    invite: { invite_id: 'inv_9Jc4Vx7Rm2Lq8Np', token: b64url(invite), token_hash_hex: hexOf(sha256(invite)) },
    owner_grant_cancel: { grant_id: 'og_2Hs6Dp9Fw3Zt5Gy', token: b64url(grant), token_hash_hex: hexOf(sha256(grant)) },
    uid: [
      { scope_id: 's1', provider: 'google', sub: '1098765432', path: 's1#google#1098765432#0', uid: b64url(uidOf('s1', 'google', '1098765432')) },
      { scope_id: 's1', provider: 'google', sub: '1098765432', path: 's1#google#1098765432#3', uid: b64url(uidOf('s1', 'google', '1098765432')) },
      { scope_id: 's2', provider: 'google', sub: '1098765432', path: 's2#google#1098765432#0', uid: b64url(uidOf('s2', 'google', '1098765432')) },
      { scope_id: 'global', provider: 'email', sub: 'e1.AbCdEf', path: 'global#email#e1.AbCdEf#1', uid: b64url(uidOf('global', 'email', 'e1.AbCdEf')) },
    ],
    jcs: [
      {
        input_json: '{"numbers":[333333333.33333329,1E30,4.50,2e-3,0.000000000000000000000000001],"string":"\\u20ac$\\u000F\\u000aA\'\\u0042\\u0022\\u005c\\\\\\"\\/","literals":[null,true,false]}',
        canonical: jcs(JSON.parse('{"numbers":[333333333.33333329,1E30,4.50,2e-3,0.000000000000000000000000001],"string":"\\u20ac$\\u000F\\u000aA\'\\u0042\\u0022\\u005c\\\\\\"\\/","literals":[null,true,false]}')),
      },
      {
        input_json: '{"\\u20ac":"Euro Sign","\\r":"Carriage Return","\\ufb33":"Hebrew Letter Dalet With Dagesh","1":"One","\\ud83d\\ude00":"Emoji: Grinning Face","\\u0080":"Control","\\u00f6":"Latin Small Letter O With Diaeresis"}',
        canonical: jcs(JSON.parse('{"\\u20ac":"Euro Sign","\\r":"Carriage Return","\\ufb33":"Hebrew Letter Dalet With Dagesh","1":"One","\\ud83d\\ude00":"Emoji: Grinning Face","\\u0080":"Control","\\u00f6":"Latin Small Letter O With Diaeresis"}')),
      },
      { input_json: '{"b":[1,{"z":-0,"a":1e21}],"a":"\\u0001x"}', canonical: jcs(JSON.parse('{"b":[1,{"z":-0,"a":1e21}],"a":"\\u0001x"}')) },
    ],
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, JSON.stringify(buildVectors(), null, 2) + '\n');
  console.log(`wrote ${OUT}`);
}
